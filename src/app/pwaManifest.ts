/**
 * Web app manifest and browser-chrome colours for the installed PWA.
 *
 * Kept outside vite.config.ts so a host test (pwaAssets.node.test.ts) can
 * check names, colours and icon references without loading the Vite plugin
 * stack. Plain data only: this file is type-checked both as app code and as
 * part of the Node-side Vite config, so it must not use DOM or Node APIs.
 *
 * Colours: the app is dark-first, so the OS chrome and splash screen use the
 * page background. Keep in sync with --dim8-bg / --color-bg in
 * src/styles/tokens.css and the theme-color in index.html (the host test
 * enforces this).
 *
 * Icons are generated by scripts/generate-icons.mjs (`npm run icons`).
 *
 * Deployment path: production builds are published by GitHub Pages under the
 * repository subpath, so the app, manifest and service worker all live below
 * GITHUB_PAGES_BASE (vite.config.ts uses it as Vite's `base`). The manifest's
 * `id`, `start_url` and `scope` are derived from the same base so the
 * installed app's identity and navigation scope always match where the
 * service worker is registered. Icon `src` values stay relative: browsers
 * resolve them against the manifest URL, which is already under the base.
 */
export const THEME_COLOR = '#010100'
export const BACKGROUND_COLOR = '#010100'

/**
 * Path the production build is served from on GitHub Pages
 * (https://dimension-eight-labs.github.io/dim8-m8trx-loyalty-card/).
 * Must start and end with `/`. Only the path is configured here; the
 * origin is never hardcoded in application code.
 */
export const GITHUB_PAGES_BASE = '/dim8-m8trx-loyalty-card/'

/** Build the web app manifest for an app served from `base`. */
export function createPwaManifest(base: string) {
  return {
    id: base,
    name: 'M8TRX',
    short_name: 'M8TRX',
    description: 'M8TRX by DIM8 Labs — a simple, offline-first wallet for your loyalty cards.',
    lang: 'en',
    start_url: base,
    scope: base,
    display: 'standalone',
    orientation: 'portrait',
    theme_color: THEME_COLOR,
    background_color: BACKGROUND_COLOR,
    icons: [
      { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
      { src: 'maskable-icon-512x512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
    ],
  } as const
}

/** The manifest exactly as the production (GitHub Pages) build emits it. */
export const PWA_MANIFEST = createPwaManifest(GITHUB_PAGES_BASE)
